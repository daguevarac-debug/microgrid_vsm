"""BAT26-50: regenerate cited figures from BAT26-45/46 ORIGINAL CSV and JSON.

No hard-coded scientific results, interpolation or guessed daily histories.
BAT26-46 SoC(t) is an original PNG generated by its committed runner and
copied unchanged with a SHA-256 provenance record. Matplotlib renders other
figures from source CSVs. Nothing modifies the model or original evidence.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
import shutil
import subprocess
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


REPO = Path(__file__).resolve().parents[2]
OUT_PARENT = REPO / "outputs" / "analysis" / "bat26_50_figures"
BAT45_FIELDS = {
    "cycles", "soh_cycling_pct", "soh_calendar_pct", "qeff_cycling_ah",
    "qeff_calendar_ah", "efc_blast", "nominal_efc_from_soc",
    "efc_from_case_throughput", "synthetic_throughput_ah",
}
BAT46_FIELDS = {
    "checkpoint_cycles", "qeff_at_checkpoint_ah", "soh_at_checkpoint_pct",
    "soc_final", "ideal_usable_ah_soc_0p6_to_0p1",
    "ideal_autonomy_h_at_8a_soc_0p6_to_0p1",
    "terminal_energy_Wh_modelled", "battery_port_current_a",
}
CHECKPOINTS = (0, 100, 500, 1000)


def _hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _read_csv(path: Path, required: set[str]) -> list[dict]:
    if not path.is_file():
        raise FileNotFoundError(f"Required original CSV missing: {path}")
    with path.open("r", encoding="utf-8-sig", newline="") as file:
        reader = csv.DictReader(file)
        fields = set(reader.fieldnames or [])
        if not required <= fields:
            raise ValueError(f"{path}: missing columns {sorted(required - fields)}")
        out = []
        for k, raw in enumerate(reader, start=2):
            parsed = {}
            for key in required:
                try:
                    parsed[key] = float(raw[key])
                except (TypeError, ValueError):
                    raise ValueError(f"{path} row {k}: invalid numeric {key}") from None
            if not all(np.isfinite(v) for v in parsed.values()):
                raise ValueError(f"{path} row {k}: nonfinite input")
            out.append(parsed)
    if not out:
        raise ValueError(f"{path}: empty source")
    return out


def _read_json(path: Path, task: str) -> dict:
    if not path.is_file():
        raise FileNotFoundError(f"Required original summary missing: {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("task") != task or data.get("status") != "PASS":
        raise ValueError(f"{path}: unexpected task or non-PASS source status")
    return data


def _verify_bat45(rows: list[dict], summary: dict) -> dict[int, dict]:
    days = np.asarray([r["cycles"] for r in rows])
    if not (len(days) >= 1001 and days[0] == 0 and days[-1] == 1000
            and np.array_equal(days, np.arange(1001))):
        raise ValueError("BAT26-45 requires original full 0..1000 daily history; no interpolation")
    for key in ("efc_blast", "nominal_efc_from_soc",
                "efc_from_case_throughput", "synthetic_throughput_ah"):
        v = np.asarray([r[key] for r in rows])
        if v[0] < -1e-9 or np.any(np.diff(v) < -1e-8):
            raise ValueError(f"BAT26-45 nonmonotone counter {key}")
    for key in ("soh_cycling_pct", "soh_calendar_pct",
                "qeff_cycling_ah", "qeff_calendar_ah"):
        v = np.asarray([r[key] for r in rows])
        if np.any(v <= 0) or np.any(np.diff(v) > 1e-8):
            raise ValueError(f"BAT26-45 invalid aging trace {key}")
        if not np.isclose(rows[-1][key], float(summary["final"][key]), atol=1e-8, rtol=0):
            raise ValueError(f"BAT26-45 final summary/history mismatch for {key}")
    if not np.allclose(
        [r["efc_from_case_throughput"] for r in rows],
        [r["synthetic_throughput_ah"] / (2 * 44.1) for r in rows],
        atol=1e-9, rtol=0,
    ):
        raise ValueError("BAT26-45 EFC_Ah reference and throughput inconsistent")
    return {int(r["cycles"]): r for r in rows}


def _verify_bat46(rows: list[dict], summary: dict, bat45: dict[int, dict]) -> None:
    if len(rows) != 4 or tuple(int(r["checkpoint_cycles"]) for r in rows) != CHECKPOINTS:
        raise ValueError("BAT26-46 must contain exactly checkpoints 0,100,500,1000")
    if len(summary.get("battery_port", [])) != 4:
        raise ValueError("BAT26-46 full battery-port summary missing")
    for row, orig in zip(rows, summary["battery_port"]):
        cycle = int(row["checkpoint_cycles"])
        q_source = bat45[cycle]["qeff_cycling_ah"]
        q_report = row["qeff_at_checkpoint_ah"]
        if abs(q_report - q_source) > 0.00051:
            raise ValueError(f"BAT26-46 Qeff not compatible with BAT26-45 rounded checkpoint {cycle}")
        if not np.isclose(row["soc_final"], float(orig["soc_final"]), atol=1e-8, rtol=0):
            raise ValueError(f"BAT26-46 CSV/summary mismatch at checkpoint {cycle}")
        if not np.isclose(row["battery_port_current_a"], 8, atol=1e-10):
            raise ValueError("BAT26-46 was not a matched +8A 2p battery-port discharge")


def _style(ax, *, xlabel: str, ylabel: str, title: str) -> None:
    ax.set(xlabel=xlabel, ylabel=ylabel, title=title)
    ax.grid(alpha=0.25)
    ax.legend(loc="best")


def _render(out: Path, rows45: list[dict], rows46: list[dict]) -> list[str]:
    days = np.asarray([x["cycles"] for x in rows45])
    soh = np.asarray([x["soh_cycling_pct"] for x in rows45])
    qcy = np.asarray([x["qeff_cycling_ah"] for x in rows45])
    qrest = np.asarray([x["qeff_calendar_ah"] for x in rows45])
    figs = []

    fig, ax = plt.subplots(figsize=(10, 6))
    ax.plot([x["efc_blast"] for x in rows45], soh, lw=2,
            label="Caso ciclado / eje EFC nativo BLAST")
    _style(ax, xlabel="EFC interno BLAST (adimensional)", ylabel="SoH relativo a 66 Ah (%)",
           title="BAT26-45: envejecimiento sintético frente al EFC BLAST")
    fig.tight_layout(); name="fig01_soh_vs_efc_blast.png"
    fig.savefig(out / name, dpi=180); plt.close(fig); figs.append(name)

    fig, ax = plt.subplots(figsize=(10, 6))
    ax.plot(days, [x["nominal_efc_from_soc"] for x in rows45], lw=2,
            label="Excursión geométrica de SoC (histórico «EFC nominal»)")
    ax.plot(days, [x["efc_from_case_throughput"] for x in rows45], lw=2,
            label="EFC por throughput en Ah / Qref=44.1 Ah")
    ax.plot(days, [x["efc_blast"] for x in rows45], lw=2,
            label="EFC interno BLAST")
    _style(ax, xlabel="Días con excursión sintética (1 por día)", ylabel="Contador adimensional",
           title="Tres definiciones de uso: NO son intercambiables")
    fig.tight_layout(); name="fig02_efc_definitions.png"
    fig.savefig(out / name, dpi=180); plt.close(fig); figs.append(name)

    fig, ax = plt.subplots(figsize=(10, 6))
    ax.plot(days, qcy, lw=2, label="Ciclado sintético")
    ax.plot(days, qrest, lw=2, label="Referencia a SoC constante 0.5")
    _style(ax, xlabel="Días del protocolo sintético", ylabel="Qeff del grupo 2p (Ah)",
           title="Capacidad efectiva; contraste no aísla mecanismo cíclico")
    fig.tight_layout(); name="fig03_capacity_vs_days.png"
    fig.savefig(out / name, dpi=180); plt.close(fig); figs.append(name)

    fig, ax = plt.subplots(figsize=(10, 6))
    x = np.asarray([r["checkpoint_cycles"] for r in rows46])
    usable = np.asarray([r["ideal_usable_ah_soc_0p6_to_0p1"] for r in rows46])
    ax.plot(x, usable, marker="o", lw=2, label="Desde SoC=0.6 hasta 0.1")
    _style(ax, xlabel="Días/ciclos sintéticos previos", ylabel="Carga utilizable ideal 2p (Ah)",
           title="Pérdida de reserva de carga en el puerto de batería")
    fig.tight_layout(); name="fig05_usable_charge_ah.png"
    fig.savefig(out / name, dpi=180); plt.close(fig); figs.append(name)

    fig, ax = plt.subplots(figsize=(10, 6))
    energy = np.asarray([r["terminal_energy_Wh_modelled"] for r in rows46])
    ax.plot(x, energy, marker="o", lw=2, label="Energía terminal transferida en 1 h a +8 A")
    _style(ax, xlabel="Días/ciclos sintéticos previos", ylabel="Energía terminal transferida (Wh)",
           title="1RC provisional: NO es energía máxima ni energía entregada al bus")
    fig.tight_layout(); name="fig06_terminal_energy_fixed_8Ah.png"
    fig.savefig(out / name, dpi=180); plt.close(fig); figs.append(name)
    return figs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bat45-dir", type=Path, required=True)
    parser.add_argument("--bat46-dir", type=Path, required=True)
    args = parser.parse_args()
    source45, source46 = args.bat45_dir.resolve(), args.bat46_dir.resolve()
    csv45, sum45 = source45 / "cycle_history.csv", source45 / "summary.json"
    csv46, sum46 = source46 / "comparison.csv", source46 / "summary.json"
    soc_figure = source46 / "soc_same_current.png"
    if not soc_figure.is_file():
        raise FileNotFoundError("BAT26-46 original SoC(t) figure missing: cannot reconstruct from endpoints")
    rows45 = _read_csv(csv45, BAT45_FIELDS)
    rows46 = _read_csv(csv46, BAT46_FIELDS)
    meta45, meta46 = _read_json(sum45, "BAT26-45"), _read_json(sum46, "BAT26-46")
    by_day = _verify_bat45(rows45, meta45)
    _verify_bat46(rows46, meta46, by_day)

    out = OUT_PARENT / datetime.now(timezone.utc).strftime("run_%Y%m%dT%H%M%S_%fZ")
    out.mkdir(parents=True, exist_ok=False)
    figs = _render(out, rows45, rows46)
    # Preserve the original verified SoC-vs-time PNG, not a fabricated straight-line plot.
    copied = "fig04_soc_vs_time_original_bat46.png"
    shutil.copyfile(soc_figure, out / copied)
    figs.insert(3, copied)

    curated = out / "checkpoints.csv"
    with curated.open("w", newline="", encoding="utf-8") as file:
        fields = ["cycles", "soh_pct", "qeff_ah", "efc_blast",
                  "soc_excursions_equiv", "efc_case_ref_ah",
                  "soc_final_after_1h_8A", "usable_ah",
                  "ideal_autonomy_h_8A", "energy_terminal_Wh_same_8Ah"]
        writer = csv.DictWriter(file, fieldnames=fields)
        writer.writeheader()
        for r46 in rows46:
            cyc = int(r46["checkpoint_cycles"])
            r45 = by_day[cyc]
            writer.writerow(dict(
                cycles=cyc, soh_pct=r45["soh_cycling_pct"],
                qeff_ah=r45["qeff_cycling_ah"],
                efc_blast=r45["efc_blast"],
                soc_excursions_equiv=r45["nominal_efc_from_soc"],
                efc_case_ref_ah=r45["efc_from_case_throughput"],
                soc_final_after_1h_8A=r46["soc_final"],
                usable_ah=r46["ideal_usable_ah_soc_0p6_to_0p1"],
                ideal_autonomy_h_8A=r46["ideal_autonomy_h_at_8a_soc_0p6_to_0p1"],
                energy_terminal_Wh_same_8Ah=r46["terminal_energy_Wh_modelled"],
            ))
    manifest = {
        "task": "BAT26-50", "status": "PASS",
        "source_bat45_status": meta45["status"],
        "source_bat46_status": meta46["status"],
        "source_git_shas": {"BAT26-45": meta45.get("git_head"),
                            "BAT26-46": meta46.get("git_head")},
        "source_files": {
            str(p): _hash(p)
            for p in (csv45, sum45, csv46, sum46, soc_figure)
        },
        "code_git_sha": subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=REPO, capture_output=True,
            text=True, check=False,
        ).stdout.strip(),
        "script_sha256": _hash(Path(__file__)),
        "python": sys.version.split()[0],
        "matplotlib": matplotlib.__version__,
        "figures": {name: _hash(out / name) for name in figs},
        "curated_csv": {"name": curated.name, "sha256": _hash(curated)},
        "limitations": [
            "BAT26-45 and BAT26-46 are synthetic, not experimental measurements.",
            "BLAST EFC, normalized SoC excursions and EFC of Ah with fixed Qref differ.",
            "BAT26-45 cycling/calendar comparators differ in SoC stress.",
            "SoC(t) PNG is copied unchanged from BAT26-46 original numerical solver.",
            "1RC terminal Wh is energy transferred for equal 8Ah, not maximum stored energy.",
            "No DC/DC/pack/IEEE33 dynamic physical energy conversion was validated.",
        ],
    }
    (out / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2, allow_nan=False) + "\n",
        encoding="utf-8",
    )
    print(f"BAT26-50 PASS | figures={len(figs)} | {out.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
